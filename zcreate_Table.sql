CREATE TABLE Robot (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre VARCHAR2(100) NOT NULL,
    tipo VARCHAR2(100) NOT NULL,
    estado NUMBER(1) DEFAULT 0 NOT NULL
);

CREATE TABLE log (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR2(255) NOT NULL,
    instruccion VARCHAR2(255) NOT NULL,
    fecha TIMESTAMP DEFAULT SYSTIMESTAMP,
    robot_id NUMBER,
    CONSTRAINT fk_log_robot FOREIGN KEY (robot_id) REFERENCES Robot(id)
);

CREATE TABLE Movimiento (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    x FLOAT NOT NULL,
    y FLOAT NOT NULL,
    z FLOAT NOT NULL,
    pitch FLOAT NOT NULL,
    roll FLOAT NOT NULL,
    yaw FLOAT NOT NULL,
    log_id NUMBER,
    CONSTRAINT fk_movimiento_log FOREIGN KEY (log_id) REFERENCES log(id)
);

CREATE TABLE Cinta (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direccion VARCHAR2(255) NOT NULL,
    velocidad FLOAT NOT NULL,
    estado NUMBER(1) DEFAULT 0 NOT NULL,
    robot_id NUMBER,
    CONSTRAINT fk_cinta_robot FOREIGN KEY (robot_id) REFERENCES Robot(id)
);

CREATE TABLE Sensores (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado NUMBER(1) DEFAULT 0 NOT NULL,
    robot_id NUMBER,
    CONSTRAINT fk_sensores_robot FOREIGN KEY (robot_id) REFERENCES Robot(id)
);